import { execSync } from "child_process";
import { writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const css = execSync(
  `npx tailwindcss -i "${join(root, "src", "embed.css")}" --minify`,
  { cwd: root, encoding: "utf-8" },
)
  .trim()
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`");

const content = `// DO NOT EDIT - generated by scripts/generate-embed-css.mjs\nexport const WIDGET_CSS = \`${css}\`;\n`;

writeFileSync(join(root, "src", "embed-css.ts"), content, "utf-8");
console.log("embed-css.ts generated");